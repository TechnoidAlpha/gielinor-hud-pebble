#!/usr/bin/env python3
"""gen_settings.py - builds the settings page the phone opens (src/pkjs/settings_page.js).

The page is src/settings/settings.html. Into it go the face's own drawing code (main.js between
the "preview: begin" and "preview: end" markers), so the live preview IS the watchface, and the
pixel fonts (atlas PNG + glyph metrics). The phone fills in __CFG__, __DATA__ and __VERSION__.

Run after editing settings.html, the drawing code or a font:   python3 tools/gen_settings.py
CI / before a release:   python3 tools/gen_settings.py --check   (fails if the page is stale)
"""
import base64, json, os, re, struct, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
MAIN = os.path.join(ROOT, "src", "embeddedjs", "main.js")
PAGE = os.path.join(ROOT, "src", "settings", "settings.html")
FONTS = os.path.join(ROOT, "src", "embeddedjs", "fonts")
OUT = os.path.join(ROOT, "src", "pkjs", "settings_page.js")


def face_code():
    src = open(MAIN, encoding="utf-8").read()
    a = src.index("// ==== preview: begin ====")
    b = src.index("// ==== preview: end ====")
    body = src[src.index("\n", a) + 1:b]
    out = []
    for line in body.split("\n"):
        s = line.strip()
        if s and not s.startswith("//"):   # full-line comments and indentation only: code is untouched
            out.append(s)
    return "\n".join(out)


def font(name):
    b = open(os.path.join(FONTS, name + ".fnt"), "rb").read()
    i, g = 4, {}
    while i < len(b):
        kind, n = b[i], struct.unpack("<I", b[i + 1:i + 5])[0]
        if kind == 4:
            for k in range(i + 5, i + 5 + n, 20):
                cid, x, y, w, h, xo, yo, xa, _p, _c = struct.unpack("<IHHHHhhhBB", b[k:k + 20])
                g[cid] = [x, y, w, h, xo, yo, xa]
        i += 5 + n
    png = base64.b64encode(open(os.path.join(FONTS, name + ".png"), "rb").read()).decode()
    return {"img": "data:image/png;base64," + png, "g": g}


def render():
    page = open(PAGE, encoding="utf-8").read()
    page = re.sub(r"<!--.*?-->\n?", "", page, count=1, flags=re.S)        # the header comment
    page = "\n".join(l.strip() for l in page.split("\n") if l.strip())
    fonts = {n: font(n) for n in ("px-n", "px-m", "px-clk", "px-n3", "px-c5")}
    for token in ("/*FACE*/", "/*FONTS*/null"):
        if page.count(token) != 1:
            sys.exit("settings.html must contain %s exactly once" % token)
    page = page.replace("/*FONTS*/null", json.dumps(fonts, separators=(",", ":")))
    page = page.replace("/*FACE*/", face_code())
    return ("// GENERATED by tools/gen_settings.py from src/settings/settings.html, main.js and the fonts.\n"
            "// Do not edit by hand.\nmodule.exports = " + json.dumps(page, ensure_ascii=False) + ";\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("src/pkjs/settings_page.js is stale: run python3 tools/gen_settings.py")
        print("settings_page.js is up to date")
    else:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote %s (%d bytes)" % (os.path.relpath(OUT, ROOT), len(text.encode("utf-8"))))
