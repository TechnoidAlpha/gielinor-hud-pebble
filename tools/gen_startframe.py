#!/usr/bin/env python3
"""gen_startframe.py - the glyph tables the C start frame draws with (src/c/startframe.h).

The C side paints the face's frame, clock and date before the JS machine has started (see
src/c/mdbl.c). Its glyphs come from the SAME atlases the watch draws with
(src/embeddedjs/fonts/*.fnt + .png), so the hand-over to JS changes no pixel.

Run after any font change:   python3 tools/gen_startframe.py
CI / before a release:       python3 tools/gen_startframe.py --check   (fails if the header is stale)
"""
import os, struct, sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FONTS = os.path.join(ROOT, "src", "embeddedjs", "fonts")
OUT = os.path.join(ROOT, "src", "c", "startframe.h")

# what the start frame writes: the clock, "Mon 2 Nov" and the chatbox speaker
NEED = {
    "clk": "0123456789:",
    "m": "0123456789 SunMonTueWedThuFriSatJanFebMarAprMayJunJulAugSepOctNovDec",
    "n": "Gielinor: ",
}
FILES = {"clk": "px-clk", "m": "px-m", "n": "px-n"}


def read_fnt(path):
    b = open(path, "rb").read()
    if b[:4] != b"BMF\x03":
        sys.exit("%s: not a binary BMFont v3 file" % path)
    i, chars = 4, {}
    while i < len(b):
        kind, n = b[i], struct.unpack("<I", b[i + 1:i + 5])[0]
        blk = b[i + 5:i + 5 + n]
        i += 5 + n
        if kind == 4:
            for k in range(0, n, 20):
                cid, x, y, w, h, xo, yo, xa, _pg, _ch = struct.unpack("<IHHHHhhhBB", blk[k:k + 20])
                chars[cid] = (x, y, w, h, xo, yo, xa)
    return chars


def font_table(key):
    chars = read_fnt(os.path.join(FONTS, FILES[key] + ".fnt"))
    alpha = Image.open(os.path.join(FONTS, FILES[key] + ".png")).convert("RGBA").getchannel("A")
    bits, glyphs = [], []
    for ch in sorted(set(NEED[key]), key=ord):
        if ord(ch) not in chars:
            sys.exit("%s has no glyph for %r" % (FILES[key], ch))
        x, y, w, h, xo, yo, xa = chars[ord(ch)]
        off = len(bits)
        stride = (w + 7) // 8
        for row in range(h):
            line = [0] * stride
            for col in range(w):
                if alpha.getpixel((x + col, y + row)) >= 128:
                    line[col >> 3] |= 0x80 >> (col & 7)
            bits.extend(line)
        glyphs.append((ord(ch), w, h, xo, yo, xa, off))
    return bits, glyphs


def render():
    out = ["// GENERATED by tools/gen_startframe.py from src/embeddedjs/fonts. Do not edit by hand.",
           "#pragma once",
           "typedef struct { uint8_t ch, w, h; int8_t xo, yo; uint8_t xa; uint16_t off; } SfGlyph;",
           "typedef struct { const SfGlyph *g; uint8_t n; const uint8_t *bits; } SfFont;"]
    for key in ("clk", "m", "n"):
        bits, glyphs = font_table(key)
        out.append("static const uint8_t SF_%s_BITS[%d] = {" % (key.upper(), len(bits)))
        for k in range(0, len(bits), 24):
            out.append("  " + ",".join("0x%02x" % v for v in bits[k:k + 24]) + ",")
        out.append("};")
        out.append("static const SfGlyph SF_%s_G[%d] = {" % (key.upper(), len(glyphs)))
        for g in glyphs:
            out.append("  {%d,%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append("static const SfFont SF_%s = { SF_%s_G, %d, SF_%s_BITS };" % (key.upper(), key.upper(), len(glyphs), key.upper()))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("src/c/startframe.h is stale: run python3 tools/gen_startframe.py")
        print("startframe.h is up to date")
    else:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote %s (%d bytes)" % (os.path.relpath(OUT, ROOT), len(text)))
